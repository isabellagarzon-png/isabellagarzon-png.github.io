/**
 * Aplica el idioma especificado en la página.
 * @param {string} lang - Código de idioma ('es', 'en', 'pt')
 */
function cambiarIdioma(lang) {
  if (!translations[lang]) return;

  // 1. Guardar preferencia en localStorage para persistencia entre páginas y recargas
  try {
    localStorage.setItem('idioma_preferido', lang);
  } catch (e) {
    console.warn('No se pudo guardar la preferencia de idioma en localStorage', e);
  }

  // 2. Actualizar el atributo lang del documento HTML
  document.documentElement.lang = lang;

  // 3. Traducir todos los elementos con atributo data-i18n
  document.querySelectorAll('[data-i18n]').forEach(elemento => {
    const clave = elemento.getAttribute('data-i18n');
    if (translations[lang][clave] !== undefined) {
      elemento.innerHTML = translations[lang][clave];
    }
  });

  // 4. Actualizar textos en placeholders si existen
  document.querySelectorAll('[data-i18n-placeholder]').forEach(elemento => {
    const clave = elemento.getAttribute('data-i18n-placeholder');
    if (translations[lang][clave] !== undefined) {
      elemento.setAttribute('placeholder', translations[lang][clave]);
    }
  });

  // 5. Actualizar atributos aria-label si existen
  document.querySelectorAll('[data-i18n-aria]').forEach(elemento => {
    const clave = elemento.getAttribute('data-i18n-aria');
    if (translations[lang][clave] !== undefined) {
      elemento.setAttribute('aria-label', translations[lang][clave]);
    }
  });

  // 6. Actualizar la interfaz del selector de idiomas
  actualizarUISelectorIdioma(lang);
}

/**
 * Actualiza la UI del botón y las opciones activas del menú de idiomas.
 * @param {string} lang - Código de idioma activo ('es', 'en', 'pt')
 */
function actualizarUISelectorIdioma(lang) {
  const etiquetaLang = document.getElementById('lang-actual');
  if (etiquetaLang) {
    etiquetaLang.textContent = lang.toUpperCase();
  }

  // Actualizar clase activo en las opciones del menú
  document.querySelectorAll('.lang-option').forEach(opcion => {
    const optLang = opcion.getAttribute('data-lang');
    if (optLang === lang) {
      opcion.classList.add('activo');
      opcion.setAttribute('aria-selected', 'true');
    } else {
      opcion.classList.remove('activo');
      opcion.setAttribute('aria-selected', 'false');
    }
  });
}

/**
 * Inicializa el comportamiento del menú desplegable del traductor.
 */
function inicializarTraductor() {
  const contenedorDropdown = document.querySelector('.lang-dropdown');
  const botonLang = document.getElementById('lang-toggle-btn');
  const opcionesLang = document.querySelectorAll('.lang-option');

  // Obtener idioma guardado o predeterminado (Español)
  let idiomaInicial = 'es';
  try {
    const guardado = localStorage.getItem('idioma_preferido');
    if (guardado && translations[guardado]) {
      idiomaInicial = guardado;
    }
  } catch (e) {}

  // Aplicar idioma inicial al cargar
  cambiarIdioma(idiomaInicial);

  if (!botonLang || !contenedorDropdown) return;

  // Alternar apertura/cierre del menú al hacer clic en el botón
  botonLang.addEventListener('click', function(e) {
    e.stopPropagation();
    const abierto = contenedorDropdown.classList.toggle('abierto');
    botonLang.setAttribute('aria-expanded', abierto ? 'true' : 'false');
  });

  // Seleccionar idioma al hacer clic en una opción
  opcionesLang.forEach(opcion => {
    opcion.addEventListener('click', function(e) {
      e.stopPropagation();
      const nuevoIdioma = this.getAttribute('data-lang');
      if (nuevoIdioma) {
        cambiarIdioma(nuevoIdioma);
        contenedorDropdown.classList.remove('abierto');
        botonLang.setAttribute('aria-expanded', 'false');
      }
    });
  });

  // Cerrar el menú si se hace clic fuera de él
  document.addEventListener('click', function(e) {
    if (!contenedorDropdown.contains(e.target)) {
      contenedorDropdown.classList.remove('abierto');
      botonLang.setAttribute('aria-expanded', 'false');
    }
  });

  // Cerrar el menú con la tecla Escape por accesibilidad
  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape' && contenedorDropdown.classList.contains('abierto')) {
      contenedorDropdown.classList.remove('abierto');
      botonLang.setAttribute('aria-expanded', 'false');
      botonLang.focus();
    }
  });
}

// Inicializar cuando el DOM esté listo
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', inicializarTraductor);
} else {
  inicializarTraductor();
}
